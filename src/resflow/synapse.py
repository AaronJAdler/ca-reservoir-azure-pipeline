"""Write the Synapse serverless SQL that Bicep and the deploy script use.

Output goes to ``infra/generated/`` and is committed, so ``bicep build`` works
without running Python first. CI re-renders and fails if the committed files
are out of date.

* ``stage_run.sql``: run by the pipeline's Script activity. CETAS writes this
  run's parsed rows as Parquet under ``staging/``.
* ``checks.sql``: run by the pipeline's Lookup activity.
* ``gold_views.sql``: run once by ``scripts/deploy.ps1`` (sqlcmd, GO-separated).
"""

from __future__ import annotations

from pathlib import Path

from resflow.sqlgen import ADF_RUN_VARS, GOLD_VIEWS, render

HEADER = "-- Generated by `resflow render`. Do not edit; edit src/resflow/sql/*.sql.j2.\n"


def _stage_table() -> str:
    # Run ids are GUIDs; brackets make the hyphens legal in the table name.
    return f"stg.[run_{ADF_RUN_VARS.run_id}]"


def stage_run_sql() -> str:
    body = render("stg_parsed", "synapse")
    table = _stage_table()
    location = f"staging/reservoir_storage/run_id={ADF_RUN_VARS.run_id}/"
    return (
        HEADER
        + f"IF OBJECT_ID('{table}') IS NOT NULL DROP EXTERNAL TABLE {table};\n"
        + f"CREATE EXTERNAL TABLE {table}\n"
        + f"WITH (LOCATION = '{location}', DATA_SOURCE = lake, FILE_FORMAT = parquet_snappy)\n"
        + "AS\n"
        + body.rstrip()
        + ";\n"
        # CETAS leaves the files; the table is only a handle, so drop it.
        + f"DROP EXTERNAL TABLE {table};\n"
    )


def checks_sql() -> str:
    return HEADER + render("checks", "synapse")


def gold_views_sql() -> str:
    parts = [HEADER]
    for name in GOLD_VIEWS:
        body = render(f"gold_{name}", "synapse").rstrip()
        parts.append(f"CREATE OR ALTER VIEW gold.{name} AS\n{body};\nGO\n")
    return "\n".join(parts)


def outputs() -> dict[str, str]:
    return {
        "stage_run.sql": stage_run_sql(),
        "checks.sql": checks_sql(),
        "gold_views.sql": gold_views_sql(),
    }


def write(out_dir: Path) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for name, text in outputs().items():
        path = out_dir / name
        path.write_text(text, encoding="utf-8", newline="\n")
        written.append(path)
    return written


def stale(out_dir: Path) -> list[str]:
    """Names of generated files that differ from what would be rendered now."""
    bad = []
    for name, text in outputs().items():
        path = out_dir / name
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            bad.append(name)
    return bad
